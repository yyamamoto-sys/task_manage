// src/lib/releaseNotes.ts
//
// 【設計意図】
// 利用者向けのバージョン履歴データ（正本）。開発者向けの docs/dev/CHANGELOG.md とは別に持つ
// （読み手が違う＝開発者 vs 利用者のため統合しない。CLAUDE.md Section 11参照）。
// CHANGELOG.md の技術的な記述をそのまま転記せず、利用者が読んで「何ができるようになったか」が
// 分かる粒度に書き直したもの。内部実装のみの変更（リファクタ・テスト追加・型修正等、利用者の
// 操作や見た目が変わらないもの）は載せない。
//
// 【範囲】2026-08-12（v3.65）に全期間へ拡張した。docs/dev/CHANGELOG.md の最古のエントリ
// （2026年3月・初回プロトタイプ）まで遡って選別している。v2.21（2026-07-06）以降は元々の
// 「2026年7月以降のみ」時点から存在する19エントリがそのまま該当し、それより前（v1.0〜v2.20）
// は今回追加した5エントリのみが該当する。件数が少ない理由：この期間はDB設計・状態管理移行
// （zustand化）・エラー表示ルール等の内部アーキテクチャ整備が中心で、利用者の操作・見た目が
// 変わった回数自体が少ない（機能の大半は2026年7月以降に集中している）。
//
// 【粒度】CHANGELOG.md の1バージョン＝1エントリという対応にはしていない。同じ日・同じ話題で
// 複数回のバージョンアップがあった場合は1エントリにまとめ、version にはその範囲の最後の
// バージョンを記す（利用者にとって「その日に何が変わったか」が分かることを優先した）。
//
// 【新しい順】配列の先頭が最新。バージョンを上げるときは、この配列の先頭に自分の変更を追記する
// こと。src/lib/__tests__/releaseNotes.test.ts が「先頭のversionがAPP_VERSIONと一致するか」を
// 機械的に検査するため、追記を忘れるとテストが落ちて気づける（version.test.tsと同じ方式）。
//
// 【ダウンロード量】このファイルは VersionHistoryModal.tsx からのみ静的importされる。
// VersionHistoryModal 自体が lazyWithRetry で遅延読込されるコンポーネントのため、バージョン
// 履歴を開かない利用者はこのデータをダウンロードしない（CLAUDE.md Section 19）。

export interface ReleaseNoteEntry {
  /** 表示用のバージョン文字列（"v" 接頭辞つき）。例："v3.63" */
  version: string;
  /** リリース日（YYYY-MM-DD） */
  date: string;
  /** 一言タイトル */
  title: string;
  /** 変更点の箇条書き（利用者の操作・見た目が変わったものだけ） */
  highlights: string[];
}

